"""
Given marks in 3 subjects with weights 40%, 30%, 30%, compute the weighted average and print a grade: A
(≥85), B (≥70), C (≥50), F (below 50).
"""
a, b , c = map(float, input(" Enter the no in a line:  ").split())
v =(.4*a)+(.3*b)+(.3*c)
print(f"{v:.2f}")
